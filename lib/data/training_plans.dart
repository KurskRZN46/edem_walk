// Недельные планы тренировок под каждую футбольную позицию.
// Привязка к режиму «Нормативы»: какой позиции следуешь - такой план.

class TrainingDay {
  final String title; // название дня
  final int steps; // цель в шагах
  final String description; // что делать

  const TrainingDay(this.title, this.steps, this.description);
}

